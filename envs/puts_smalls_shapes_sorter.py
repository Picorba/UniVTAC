    @staticmethod
    def _set_prim_pose(stage, prim_path: str, pose: Pose):
        """Write a Pose to a prim using separate translate + orient ops."""

        xform = UsdGeom.Xformable.Get(stage, prim_path)
        if not xform:
            return

        p = pose.p
        w, x, y, z = pose.q

        # Clear existing ops and write translate + orient separately
        # (actor_manager already created these op types — match them)
        xform.ClearXformOpOrder()
        xform.AddTranslateOp().Set(Gf.Vec3d(float(p[0]), float(p[1]), float(p[2])))
        xform.AddOrientOp().Set(Gf.Quatd(float(w), float(x), float(y), float(z)))
