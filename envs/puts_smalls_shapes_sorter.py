"""puts_smalls_shapes_sorter — Vision-Tactile-Language-Action (VTLA) task.

2–4 small shapes are randomly selected and spawned on the table each episode.
A natural-language instruction specifies which shape the robot must grasp and
drop into a sorter block placed in front of the robot.

Shape assets generated by scripts/generate_sorter.py
(--clearance 1.0 --scale 0.01 --tess 0.05 --out ./usd_shapes):
  cube               cube.usd         (~0.22 × 0.22 × 0.30 m, Z-centred)
  cylinder           cylinder.usd     (~Ø0.22 × 0.30 m, Z-centred)
  triangular prism   triangular_prism.usd
  star               star.usd
  moon               moon.usd
  sorter block       shape_sorter.usd (~2.0 × 0.6 × 0.40 m, Z-centred)

All generated USD assets are Z-centred (CadQuery origin = geometric centre).
With --scale 0.01 each shape piece is 0.30 m tall, so the spawn pose Z must
equal half the height (0.15 m) to rest the bottom on the table surface (z≈0).

Episode flow
------------
1. N_OBJECTS_PER_EPISODE shapes are drawn at random (without replacement).
2. A target shape is chosen; a language instruction is sampled from its pool.
3. pre_move: open gripper.
4. _play_once: grasp the target shape and drop it into the sorter hole.
5. check_success: target shape is inside the sorter zone.
"""

