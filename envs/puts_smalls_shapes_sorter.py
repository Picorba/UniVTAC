    def _build_grasp_pose(self) -> tuple:
        target = self._shapes[self._target_name]
        cfg    = SHAPE_CONFIGS[self._target_name]
        obj_p  = target.get_pose().p

        if self._target_name == 'triangle' or self._target_name == 'moon' :
            base_close_axis = np.array([0.0, 1.0, 0.0])
        else :
            base_close_axis = np.array([1.0, 0.0, 0.0])
        q = self._shapes[self._target_name].get_pose().q
        w, x, y, z = float(q[0]), float(q[1]), float(q[2]), float(q[3])
        R = np.array([
            [1-2*(y*y+z*z),   2*(x*y-z*w),   2*(x*z+y*w)],
            [  2*(x*y+z*w), 1-2*(x*x+z*z),   2*(y*z-x*w)],
            [  2*(x*z-y*w),   2*(y*z+x*w), 1-2*(x*x+y*y)],
        ])
        close_axis = R @ base_close_axis
        grasp_p = obj_p \
                + np.array([0.0, 0.0, cfg['grasp_z']]) 
        
        grasp_pose = construct_grasp_pose(
            grasp_p,
            np.array([0.0, 0.0, 1.0]),
            close_axis,
        )
        contact_idx = target.register_point(pose=grasp_pose, type='contact')
        print("GRASP POSE", grasp_pose)
        return grasp_pose, contact_idx

