    def _random_init_poses(self, n: int, min_dist: float = 0.15) -> list:
        """
        Generate n non-overlapping random poses on the table, avoiding the sorter.

        x : uniform in [0.1, 1.0] — rejected if inside sorter footprint
        y : uniform in [-0.35, 0.35] — rejected if inside sorter footprint
        z : TABLE_SPAWN_Z (fixed)
        rz: uniform in [0, 2π]
        """
        MAX_ATTEMPTS = 200
        SORTER_X_MIN = 0.3

        SORTER_X_MAX = 0.7  
        SORTER_Y_MIN = -0.2
        SORTER_Y_MAX =  0.2
        SORTER_MARGIN = 0.05

        # ── Table spawn bounds ────────────────────────────────────────────────────────
        TABLE_X_MIN = 0.1
        TABLE_X_MAX = 0.75
        TABLE_Y_MIN = -0.45
        TABLE_Y_MAX =  0.45

        fx_min = SORTER_X_MIN - SORTER_MARGIN
        fx_max = SORTER_X_MAX + SORTER_MARGIN
        fy_min = SORTER_Y_MIN - SORTER_MARGIN
        fy_max = SORTER_Y_MAX + SORTER_MARGIN

        def _in_sorter(x: float, y: float) -> bool:
            return fx_min < x < fx_max and fy_min < y < fy_max

        poses = []
        while len(poses) < n:
            for _ in range(MAX_ATTEMPTS):
                x  = self.rng.uniform(TABLE_X_MIN, TABLE_X_MAX)
                y  = self.rng.uniform(TABLE_Y_MIN, TABLE_Y_MAX)
                rz = self.rng.uniform(0.0, 2 * np.pi)

                if not _in_sorter(x, y):
                    q = np.array([np.cos(rz / 2), 0.0, 0.0, np.sin(rz / 2)])
                    candidate = Pose([x, y, TABLE_SPAWN_Z], q)

                    too_close = any(
                        np.linalg.norm(candidate.p[:2] - p.p[:2]) < min_dist
                        for p in poses
                    )
                    if not too_close:
                        poses.append(candidate)
                        break
            else:
                raise RuntimeError(
                    f"Could not place object {len(poses)+1}/{n} after "
                    f"{MAX_ATTEMPTS} attempts — reduce n or min_dist."
                )

        return poses
