    def _compute_z_rotation_correction(self, shape_name: str) -> float:
        """Returns the minimum Z-rotation (radians) to align shape with its hole."""
        cfg = SHAPE_CONFIGS[shape_name]
        if cfg['canonical_axis'] is None:
            return 0.0  # cylinder: any rotation is valid

        q_obj = self._shapes[shape_name].get_pose().q  # [w, x, y, z]
        print("QUATERNION", q_obj)

        c_local = np.array(cfg['canonical_axis'], dtype=float)
        # 1. define in sorter frame
        t_sorter = np.array(cfg['target_sorter_axis'])

        # 2. get sorter rotation
        q_sorter = self._drawer.get_pose().q
        def quat_to_matrix(q):
            w, x, y, z = q
            return np.array([
                [1-2*(y*y+z*z),   2*(x*y-z*w),   2*(x*z+y*w)],
                [  2*(x*y+z*w), 1-2*(x*x+z*z),   2*(y*z-x*w)],
                [  2*(x*z-y*w),   2*(y*z+x*w), 1-2*(x*x+y*y)],
            ])
        R_sorter = quat_to_matrix(q_sorter)

        # 3. convert to world
        t_world = R_sorter @ t_sorter

        # Rotate canonical axis to world frame
        # Using scipy or manual quaternion rotation:
        w, x, y, z = q_obj
        R = np.array([
            [1-2*(y*y+z*z),   2*(x*y-z*w),   2*(x*z+y*w)],
            [  2*(x*y+z*w), 1-2*(x*x+z*z),   2*(y*z-x*w)],
            [  2*(x*z-y*w),   2*(y*z+x*w), 1-2*(x*x+y*y)],
        ])
        c_world = R @ c_local

        # Project onto XY, compute angle
        cx, cy = c_world[0], c_world[1]
        tx, ty = t_world[0], t_world[1]
        theta0 = np.arctan2(cx * ty - cy * tx, cx * tx + cy * ty)

        # Snap to best symmetric equivalent
        N = cfg['symmetry_order']
        candidates = [theta0 + k * 2 * np.pi / N for k in range(N)]
        # Wrap to [-pi, pi]
        candidates = [(a + np.pi) % (2 * np.pi) - np.pi for a in candidates]
        theta_star = min(candidates, key=abs)

        return theta_star
    
    def _play_once(self):
        """Grasp the target shape and drop it into the drawer."""
        cfg = SHAPE_CONFIGS[self._target_name]
        _, contact_idx = self._build_grasp_pose()
        # 1a. Move explicitly above the object (guaranteed hover, no cuRobo soft cost)
        obj_p = self._shapes[self._target_name].get_pose().p
        ee_now = self.atom.get_arm_pose()
        approach_extra_z = 0.25
        above_obj = Pose(
            [obj_p[0], obj_p[1], obj_p[2] + cfg['grasp_z'] + approach_extra_z],
            ee_now.q,
        )
        self.move(self.atom.move_to_pose(above_obj), time_dilation_factor=0.5)

        # 1b. Descend straight onto the grasp point
        self.move(self.atom.grasp_actor(
            self._shapes[self._target_name],
            contact_point_id=contact_idx,
            is_close=False,
        ))
        force_to_apply = self.cfg.force_slow if self._target_name == 'moon' else self.cfg.force_fast 
        pos_floor = cfg.get('grasp_pos_floor', 0.0)                                                                             
        self.move(self.atom.close_gripper(pos=pos_floor, force=force_to_apply))
        robot = self._robot_manager                                                                                                                                                                                                                                 
        fingers = robot.robot.data.joint_pos[0, robot._gripper_ids]
        print(f"[DEBUG] Finger joints: j1={fingers[0]:.5f}  j2={fingers[1]:.5f}  "                                                                                                                                                                                  
                f"asymmetry={abs(fingers[0]-fingers[1])*1000:.2f} mm")                                                                                                                                                                                                
                                                                                                                                                                                                                                                                    
        inhand = robot.get_inhand_pose(self._shapes[self._target_name])                                                                                                                                                                                             
        print(f"[DEBUG] In-hand offset (gripper-center frame): {inhand.p}")  

        
        # 2. Lift clear of neighbouring shapes and above the sorter top (0.40 m)
        # Grasp is near the piece top (~0.23 m); lift 0.25 m → EE at ~0.48 m
        self.move(self.atom.move_by_displacement(z=0.2))

        self.check_mid_failure()

        # 3. Move above the correct hole for this shape.
        # The sorter is rotated 90° around Z, so its local X axis (hole layout)
        # maps to world Y.  Apply hole_x_offset along world Y.
        drawer_p   = self._drawer.get_pose().p
        hole_y_off = cfg['hole_x_offset']
        ee_now     = self.atom.get_arm_pose()

        above_hole = Pose(
            [drawer_p[0], drawer_p[1] + hole_y_off, ee_now.p[2]],
            ee_now.q,
        )
        self.move(self.atom.move_to_pose(above_hole))
        # Correct for cuRobo FK vs Isaac Lab FK residual XY error.
       

        # 4. Lower into the hole (sorter top at 0.40 m, hole depth 0.34 m)
        # Drop by 0.15 m → EE at ~0.33 m, well inside the 0.34 m deep hole
        self.move(self.atom.move_by_displacement(z=-0.12))
        def correct_angle():
            theta = self._compute_z_rotation_correction(self._target_name)
            print("ROTATING OF THETA", theta)
            if abs(theta) > np.radians(2.0):  # 2° dead-band
                self.move(self.atom.rotate_wrist_z(theta))

        def correct_position():
            obj_p = self._shapes[self._target_name].get_pose().p
            x_err = drawer_p[0]              - obj_p[0]
            y_err = drawer_p[1] + hole_y_off - obj_p[1]
            if abs(x_err) > 0.002 or abs(y_err) > 0.002:
                self.move(self.atom.move_by_displacement(x=x_err, y=y_err), time_dilation_factor=0.5)

        SUCCESS_DESCENT = 0.1   # m — exit both loops if we descend this much
        STEP_DOWN       = 0.005 # m — per step
        STUCK_TOL       = 0.001 # m — if actual movement < this we consider it stuck

        nb_try = 0
        insertion_success = False
        while nb_try < 3 and not insertion_success:
            print("NB TRY", nb_try)
            self.move(self.atom.move_by_displacement(z=0.03), time_dilation_factor=0.5)
            correct_angle()
            correct_position()
            self.move(self.atom.move_by_displacement(z=-0.03), time_dilation_factor=0.5)
            z_start    = self._robot_manager.get_ee_pose().p[2]
            z_previous = z_start
            total_descended = 0.0

            while total_descended < SUCCESS_DESCENT:
                self.move(self.atom.move_by_displacement(z=-STEP_DOWN), time_dilation_factor=0.5)
                z_now      = self._shapes[self._target_name].get_pose().p[2]
                actual_step = z_previous - z_now
                total_descended = z_start - z_now
                if actual_step < STUCK_TOL:
                    print(f"[descent] STUCK at total={total_descended*1000:.1f} mm, retrying")
                    break
                z_previous = z_now
            else:
                insertion_success = True
                print(f"[descent] SUCCESS after {nb_try+1} tries, "
                    f"descended {total_descended*1000:.1f} mm")
                break

            nb_try += 1

        if not insertion_success:
            print(f"[descent] FAILED after {nb_try} tries")
        

        self.move(self.atom.open_gripper(force=self.cfg.force_fast, steps=40))
        # 6. Hold for final observation frames
        self.delay(10, is_save=True)

